#!/usr/bin/env bash
#
# Refresh the payload binaries embedded in Relapse.jar from upstream releases,
# then regenerate PayloadPaths.java so the jar picks up the new versions.
#
# Usage:
#   scripts/update_payloads.sh           # fetch the latest ps5-unified-autoloader
#   scripts/update_payloads.sh --check   # print what is embedded, change nothing
#
# Only the autoloader is updated automatically.  kexp and elfldr are pinned to
# builds that match the loader ABI:
#   * kexp is mapped as raw shellcode, so it must be relinked with its entry
#     point at offset 0 (ufm42/kexp + script.ld).
#   * kexp loads elfldr with `base + e_entry`, so the upstream prebuilt release
#     (e_entry = 0) cannot replace the bundled blob as-is.
# See README, "Payload versions", for how to rebuild those two.

set -euo pipefail
cd "$(dirname "$0")/.."

DEST="src/org/bdj/external"
CHECK_ONLY=0

for arg in "$@"; do
    case "$arg" in
        --check) CHECK_ONLY=1 ;;
        -h|--help)
            sed -n '2,18p' "$0" | sed 's/^# \{0,1\}//'
            exit 0 ;;
        *)
            echo "unknown argument: $arg" >&2
            exit 1 ;;
    esac
done

shopt -s nullglob
kexp_files=("$DEST"/kexp_*.bin "$DEST"/kexp-*.bin)
elfldr_files=("$DEST"/elfldr-*.elf)
autoloader_files=("$DEST"/ps5-unified-autoloader-*.elf)

print_versions() {
    echo "embedded payloads:"
    printf '  kexp       : %s\n' "${kexp_files[0]##*/}"
    printf '  elfldr     : %s\n' "${elfldr_files[0]##*/}"
    printf '  autoloader : %s\n' "${autoloader_files[0]##*/}"
}

if [ "$CHECK_ONLY" = 1 ]; then
    print_versions
    exit 0
fi

# --- fetch the newest autoloader ELF ----------------------------------------

fetch_latest_elf() { # <repo> <outdir> -> prints "<tag> <path>"
    local repo="$1" outdir="$2"
    local tag url

    if command -v gh >/dev/null 2>&1; then
        tag=$(gh release view -R "$repo" --json tagName --jq '.tagName')
        url=$(gh release view -R "$repo" --json assets \
                --jq '.assets[] | select(.name | endswith(".elf")) | .url' | head -n 1)
        if [ -z "$url" ]; then
            echo "no ELF asset in $repo $tag" >&2
            return 1
        fi
        gh release download -R "$repo" -p '*.elf' -D "$outdir" --clobber >/dev/null
    else
        local json
        json=$(curl -fsSL "https://api.github.com/repos/$repo/releases/latest")
        tag=$(printf '%s' "$json" \
              | grep -o '"tag_name": *"[^"]*"' | head -n 1 \
              | sed 's/.*"tag_name": *"//; s/"$//')
        url=$(printf '%s' "$json" | grep -o 'https://github.com/[^"]*\.elf' | head -n 1)
        if [ -z "$url" ]; then
            echo "no ELF asset in $repo latest release" >&2
            return 1
        fi
        curl -fsSL -o "$outdir/$(basename "$url")" "$url"
    fi

    local path
    path=$(ls "$outdir"/*.elf 2>/dev/null | head -n 1)
    echo "$tag $path"
}

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

echo "==> fetching latest ps5-unified-autoloader"
read -r AUTO_TAG AUTO_SRC <<< "$(fetch_latest_elf itsPLK/ps5-unified-autoloader "$TMP")"

AUTO_FILE="ps5-unified-autoloader-${AUTO_TAG}.elf"
install -m 0644 "$AUTO_SRC" "$DEST/$AUTO_FILE"
for old in "$DEST"/ps5-unified-autoloader-*.elf; do
    [ "$old" = "$DEST/$AUTO_FILE" ] || rm -f "$old"
done
echo "    $AUTO_FILE ($(stat -c%s "$DEST/$AUTO_FILE") bytes)"

# --- regenerate PayloadPaths.java -------------------------------------------

kexp_files=("$DEST"/kexp_*.bin "$DEST"/kexp-*.bin)
elfldr_files=("$DEST"/elfldr-*.elf)
autoloader_files=("$DEST"/ps5-unified-autoloader-*.elf)
for f in "${kexp_files[0]}" "${elfldr_files[0]}" "${autoloader_files[0]}"; do
    [ -f "$f" ] || { echo "missing payload: $f" >&2; exit 1; }
done

cat > "$DEST/PayloadPaths.java" <<EOF
/*
 * BD-J Relapse - embedded payload paths.
 *
 * Generated by scripts/update_payloads.sh; edit that script (or re-run it)
 * instead of hand-editing the constants so the versioned file names stay in
 * sync with what is actually embedded in Relapse.jar.
 */

package org.bdj.external;

public final class PayloadPaths {

    private PayloadPaths() {
    }

    /* kexp bootstrap shellcode, built from ufm42/kexp and relinked so the entry
     * point sits at offset 0 (kexp is mapped raw, not parsed as an ELF). */
    public static final String KEXP = "/org/bdj/external/${kexp_files[0]##*/}";

    /* elfldr served on port 9021; kexp spawns it from this blob. */
    public static final String ELFLDR = "/org/bdj/external/${elfldr_files[0]##*/}";

    /* ps5-unified-autoloader, streamed to elfldr after the exploit completes. */
    public static final String AUTOLOADER =
            "/org/bdj/external/${autoloader_files[0]##*/}";
}
EOF

print_versions
echo "regenerated $DEST/PayloadPaths.java"
